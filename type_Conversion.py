# Type Conversion
# Type conversion is the process of converting the value of one data type to another data type.

# Implicit Type Conversion
# Python automatically converts one data type to another data type when necessary.

# Explicit Type Conversion
# In explicit type conversion, the user manually converts one data type to another data type using built-in functions.

# Example of Implicit Type Conversion

x = 5
y = 10.0
z = x + y  # Implicit conversion of x to float
print(z)

# Output: 15.0

# Example of Explicit Type Conversion

x = "5"
y = 10
z = int(x) + y  # Explicit conversion of x to integer
print(z)



# Output: 15